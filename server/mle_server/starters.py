def kaggle_notebook(meta: dict[str, Any], code: str) -> dict[str, Any]:
    if meta["kind"] == "csv":
        setup = _KAGGLE_SETUP.format(expect=meta.get("data_file") or "data.csv", hint="the CSV file this project was built on",
                                     test="EXPECT in filenames")
    else:
        setup = _KAGGLE_SETUP.format(expect="class folders", hint="a folder holding one sub-folder of images per class",
                                     test='subfolders and any(f.lower().endswith((".png", ".jpg", ".jpeg", ".bmp", ".gif", ".webp")) '
                                          "for f in os.listdir(os.path.join(folder, subfolders[0])))")
    intro = (
        f"# {meta['name']}\n\nExported from ML-E.\n\n"
        "1. Upload the project's `data` folder to Kaggle as a dataset (**Datasets → New Dataset**).\n"
        "2. In this notebook choose **Add Input** and attach that dataset.\n"
        "3. Under **Settings → Accelerator** pick a GPU, then **Run All**.\n"
        "4. The trained model appears in the **Output** panel under `models/`."
    )

    def cell(kind: str, source: str) -> dict[str, Any]:
        lines = source.strip("\n").splitlines(keepends=True)
        base: dict[str, Any] = {"cell_type": kind, "metadata": {}, "source": lines}
        if kind == "code":
            base.update(execution_count=None, outputs=[])
        return base

    return {
        "nbformat": 4, "nbformat_minor": 5,
        "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                     "language_info": {"name": "python"}},
        "cells": [cell("markdown", intro), cell("code", setup), cell("code", code)],
    }
